def _ssl_contexts():
    yield None  # системные сертификаты
    try:
        import certifi  # есть в Colab, Kaggle, Anaconda
        yield ssl.create_default_context(cafile=certifi.where())
    except Exception:
        pass
    # Последний вариант: без проверки сертификата. Это безопасно только потому,
    # что каждый скачанный файл сверяется с зашитой в скрипт суммой SHA-256.
    yield ssl._create_unverified_context()


def _is_cert_error(err):
    reason = getattr(err, "reason", err)
    return isinstance(reason, ssl.SSLError) and "CERTIFICATE" in str(reason).upper()


_CURRENT = {"variant": None}


def _network_hint(url, err):
    host = urllib.parse.urlparse(url).netloc
    msg = ["Не удалось подключиться к %s (%s)." % (host, err)]
    if on_kaggle():
        msg.append(
            "Похоже, это Kaggle с выключенным интернетом. Откройте справа панель Settings → "
            "Internet и включите его (Kaggle один раз попросит подтвердить номер телефона). "
            "Если подтвердить телефон нельзя, запустите ноутбук в Colab или локально.")
    else:
        msg.append(
            "Проверьте подключение к интернету, прокси или VPN. Если GitHub недоступен, "
            "попробуйте запасной путь: python data/get_data.py --variant %s --from-official"
            % (_CURRENT["variant"] if _CURRENT["variant"] is not None else "N"))
    return "\n".join(msg)


def _urlopen(url, headers=None, timeout=60):
    req = urllib.request.Request(url, headers=dict({"User-Agent": USER_AGENT}, **(headers or {})))
    last = None
    for ctx in _ssl_contexts():
        try:
            if ctx is None:
                return urllib.request.urlopen(req, timeout=timeout)
            return urllib.request.urlopen(req, timeout=timeout, context=ctx)
        except urllib.error.HTTPError:
            raise
        except (urllib.error.URLError, ssl.SSLError) as e:
            if _is_cert_error(e):
                last = e
                continue
            raise
    raise last


def download(url, dest_path, sha256=None, size=None, label=None, retries=4):
    """Скачивает url в dest_path с докачкой, прогрессом и проверкой SHA-256."""
    dest_path = Path(dest_path)
    part = Path(str(dest_path) + ".part")
    label = label or dest_path.name
    for attempt in range(1, retries + 1):
        have = part.stat().st_size if part.exists() else 0
        if size and have > size:
            part.unlink()
            have = 0
        headers = {"Range": "bytes=%d-" % have} if have else {}
        try:
            resp = _urlopen(url, headers=headers)
        except urllib.error.HTTPError as e:
            if e.code == 416 and have:  # уже всё скачано
                resp = None
            elif e.code == 404:
                raise GetDataError(
                    "Сервер ответил 404: файла %s нет по адресу\n  %s\n"
                    "Проверьте номер варианта. Если он верный, сообщите преподавателю: "
                    "возможно, данные ещё не опубликованы." % (label, url))
            elif attempt < retries:
                say("  Сервер ответил %d, повтор через %d с..." % (e.code, 3 * attempt))
                time.sleep(3 * attempt)
                continue
            else:
                raise GetDataError("Сервер ответил ошибкой %d при скачивании %s" % (e.code, url))
        except (urllib.error.URLError, socket.timeout, ConnectionError, OSError) as e:
            if attempt < retries and not isinstance(getattr(e, "reason", None), socket.gaierror):
                say("  Нет связи (%s), повтор через %d с..." % (getattr(e, "reason", e), 3 * attempt))
                time.sleep(3 * attempt)
                continue
            raise GetDataError(_network_hint(url, getattr(e, "reason", e)))
        if resp is not None:
            if have and getattr(resp, "status", resp.getcode()) != 206:
                have = 0  # сервер не поддержал докачку
            total = size
            if not total:
                cl = resp.headers.get("Content-Length")
                total = (int(cl) + have) if cl else None
            mode = "ab" if have else "wb"
            done = have
            t0 = time.time()
            last_print = 0.0
            try:
                with open(str(part), mode) as f:
                    while True:
                        block = resp.read(1 << 16)
                        if not block:
                            break
                        f.write(block)
                        done += len(block)
                        now = time.time()
                        if now - last_print > 0.5:
                            last_print = now
                            speed = (done - have) / max(now - t0, 1e-6)
                            if total:
                                say("\r  %s: %s из %s (%3d%%), %s/с   " % (
                                    label, _human(done), _human(total), 100 * done // total, _human(speed)), end="")
                            else:
                                say("\r  %s: %s, %s/с   " % (label, _human(done), _human(speed)), end="")
            except (socket.timeout, ConnectionError, OSError) as e:
                if attempt < retries:
                    say("\n  Связь прервалась (%s), докачиваю..." % e)
                    time.sleep(2)
                    continue
                raise GetDataError(_network_hint(url, e))
            finally:
                resp.close()
            say("\r  %s: %s, готово.%s" % (label, _human(done), " " * 30))
        if size and part.stat().st_size < size and attempt < retries:
            say("  Файл скачан не полностью, докачиваю...")
            continue
        if sha256:
            got = _sha256_file(str(part))
            if got != sha256:
                part.unlink()
                if attempt < retries:
                    say("  Контрольная сумма не совпала, качаю заново...")
                    continue
                raise GetDataError(
                    "Контрольная сумма %s не совпала (ожидалась %s, получена %s). "
                    "Файл повреждён при передаче или на сервере лежит другая версия." % (label, sha256, got))
        os.replace(str(part), str(dest_path))
        return dest_path
    raise GetDataError("Не удалось скачать %s" % url)


