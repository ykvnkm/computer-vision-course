def _read_marker(vdir):
    try:
        with open(str(Path(vdir) / MARKER), encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def _is_installed(vdir, n):
    m = _read_marker(vdir)
    if not m or m.get("variant") != n or m.get("dataset_version") != DATASET_VERSION:
        return False
    if not (Path(vdir) / "labels.csv").is_file() or not (Path(vdir) / "images").is_dir():
        return False
    n_files = sum(1 for p in (Path(vdir) / "images").iterdir() if p.is_file())
    return n_files == m.get("n_images")


def _write_marker(vdir, n, source, zip_sha=None):
    info = _load_json(Path(vdir) / "variant.json")
    marker = {
        "variant": n, "dataset_version": DATASET_VERSION, "source": source,
        "zip_sha256": zip_sha, "n_images": info.get("n_images"),
        "content_sha256": content_digest(vdir),
        "installed_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    with open(str(Path(vdir) / MARKER), "w", encoding="utf-8") as f:
        json.dump(marker, f, ensure_ascii=False, indent=2)
    return marker


def _load_json(path):
    with open(str(path), encoding="utf-8") as f:
        return json.load(f)


def _move_aside(vdir):
    i = 1
    while True:
        bak = Path("%s.old%d" % (vdir, i) if i > 1 else "%s.old" % vdir)
        if not bak.exists():
            os.replace(str(vdir), str(bak))
            say("  Старая папка %s переименована в %s" % (vdir, bak.name))
            return
        i += 1


def _free_space_check(folder, need_bytes):
    try:
        free = shutil.disk_usage(str(folder)).free
    except OSError:
        return
    if free < need_bytes:
        raise GetDataError("Мало места на диске: нужно около %s, свободно %s в %s"
                           % (_human(need_bytes), _human(free), folder))


def _extract_zip(zip_path, dest, n):
    name = vname(n)
    tmp = Path(tempfile.mkdtemp(prefix=".%s-" % name, dir=str(dest)))
    try:
        with zipfile.ZipFile(str(zip_path)) as zf:
            for info in zf.infolist():
                fn = info.filename
                if not fn.startswith(name + "/") or ".." in fn.split("/") or fn.startswith("/"):
                    raise GetDataError("В архиве посторонний путь: %s" % fn)
            zf.extractall(str(tmp))
        return tmp / name, tmp
    except zipfile.BadZipFile:
        shutil.rmtree(str(tmp), ignore_errors=True)
        raise GetDataError("Архив %s повреждён. Удалите его и запустите скрипт ещё раз." % zip_path)
    except Exception:
        shutil.rmtree(str(tmp), ignore_errors=True)
        raise


def _finalize(staged, tmp_root, final):
    if final.exists():
        _move_aside(final)
    os.replace(str(staged), str(final))
    shutil.rmtree(str(tmp_root), ignore_errors=True)


def _find_local(roots, n, max_depth=4):
    """Ищет variant_XX.zip или распакованную папку variant_XX в каталогах roots."""
    name = vname(n)
    found_dir = None
    for root in roots:
        root = os.path.abspath(str(root))
        if not os.path.isdir(root):
            continue
        base_depth = root.rstrip(os.sep).count(os.sep)
        for cur, dirs, files in os.walk(root):
            if cur.count(os.sep) - base_depth >= max_depth:
                dirs[:] = []
            if name + ".zip" in files:
                return "zip", Path(cur) / (name + ".zip")
            if found_dir is None and os.path.basename(cur) == name and "labels.csv" in files:
                found_dir = Path(cur)
            dirs.sort()
    if found_dir is not None:
        return "dir", found_dir
    return None, None


def _install_from_zip(zip_path, dest, n, spec, verify=True):
    if verify and spec.get("zip_sha256"):
        say("  Проверяю контрольную сумму %s..." % Path(zip_path).name)
        got = _sha256_file(str(zip_path))
        if got != spec["zip_sha256"]:
            raise GetDataError("Контрольная сумма %s не совпала: это не тот архив или он повреждён." % zip_path)
    _free_space_check(dest, int(spec.get("zip_size", 0) * 1.2))
    say("  Распаковываю в %s ..." % (dest / vname(n)))
    staged, tmp = _extract_zip(zip_path, dest, n)
    if spec.get("content_sha256") and content_digest(staged) != spec["content_sha256"]:
        shutil.rmtree(str(tmp), ignore_errors=True)
        raise GetDataError("Содержимое архива не совпало с ожидаемым. Скачайте вариант заново с --force.")
    _write_marker(staged, n, "release", spec.get("zip_sha256"))
    final = dest / vname(n)
    _finalize(staged, tmp, final)
    return final


def _install_from_dir(src_dir, dest, n, spec):
    say("  Копирую готовую папку %s ..." % src_dir)
    if spec.get("content_sha256") and content_digest(src_dir) != spec["content_sha256"]:
        raise GetDataError("Папка %s не совпадает с эталонным вариантом %02d (другая версия данных?)." % (src_dir, n))
    tmp = Path(tempfile.mkdtemp(prefix=".%s-" % vname(n), dir=str(dest)))
    staged = tmp / vname(n)
    shutil.copytree(str(src_dir), str(staged), ignore=shutil.ignore_patterns(MARKER))
    _write_marker(staged, n, "release", spec.get("zip_sha256"))
    final = dest / vname(n)
    _finalize(staged, tmp, final)
    return final


def ensure_variant(n, dest=None, source=None, force=False, from_official=False,
                   official_source=None, quiet=False):
    """Гарантирует, что вариант n лежит в dest/variant_NN, и возвращает путь к нему.

    n         номер варианта (1..22, 0 у преподавателя)
    dest      папка, в которой появится variant_NN (по умолчанию папка со скриптом)
    source    папка с variant_NN.zip / variant_NN или базовый URL вместо GitHub
    force     скачать и распаковать заново
    from_official  собрать вариант из официальных архивов Oxford
    """
    n = _check_variant_number(n)
    _CURRENT["variant"] = n
    spec = VARIANTS[n]
    dest = Path(dest).expanduser().resolve() if dest else _default_dest()
    dest.mkdir(parents=True, exist_ok=True)
    final = dest / vname(n)

    if not force and _is_installed(final, n):
        if not quiet:
            say("Вариант %02d уже на месте: %s" % (n, final))
        return final
    if force and final.exists():
        shutil.rmtree(str(final))

    if from_official:
        return build_from_official(n, dest, official_source)

    say("Вариант %02d: %s" % (n, ", ".join(spec["breeds"])))

    # 1. Явно указанный источник
    if source and not str(source).startswith(("http://", "https://")):
        kind, path = _find_local([source], n)
        if kind == "zip":
            return _done(_install_from_zip(path, dest, n, spec))
        if kind == "dir":
            return _done(_install_from_dir(path, dest, n, spec))
        raise GetDataError("В папке %s нет ни %s.zip, ни распакованной папки %s." % (source, vname(n), vname(n)))

    # 2. Kaggle: датасет-зеркало, подключённое к ноутбуку
    if not source and on_kaggle():
        kind, path = _find_local(["/kaggle/input"], n, max_depth=5)
        if kind == "zip":
            say("  Нашёл архив в подключённых данных Kaggle: %s" % path)
            return _done(_install_from_zip(path, dest, n, spec))
        if kind == "dir":
            say("  Нашёл вариант в подключённых данных Kaggle: %s" % path)
            return _done(_install_from_dir(path, dest, n, spec))

    # 3. Скачивание (GitHub Releases или указанный URL)
    base = str(source) if source else RELEASE_URL
    if not base.endswith("/"):
        base += "/"
    url = base + vname(n) + ".zip"
    _free_space_check(dest, int(spec.get("zip_size", 0) * 2.3))
    zip_path = dest / (vname(n) + ".zip")
    if zip_path.exists() and spec.get("zip_sha256") and _sha256_file(str(zip_path)) == spec["zip_sha256"]:
        say("  Архив уже скачан: %s" % zip_path)
    else:
        say("  Скачиваю %s" % url)
        download(url, zip_path, spec.get("zip_sha256"), spec.get("zip_size"), label=zip_path.name)
    final = _install_from_zip(zip_path, dest, n, spec, verify=False)
    try:
        zip_path.unlink()
    except OSError:
        pass
    return _done(final)


def _done(final):
    say("Готово: %s (%d изображений)" % (final, _load_json(final / "variant.json")["n_images"]))
    return final


