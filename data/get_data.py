def vname(n):
    return "variant_%02d" % int(n)


def breed_of(stem):
    return stem.rsplit("_", 1)[0]


def species_of(breed):
    return BREEDS[breed][0]


def sort_breeds(breeds):
    """Сначала кошки, потом собаки, внутри по алфавиту. Индекс = class_id."""
    return sorted(breeds, key=lambda b: (species_of(b) != "cat", b.lower()))


def natural_key(filename):
    stem = os.path.splitext(filename)[0]
    b, _, num = stem.rpartition("_")
    try:
        return (b.lower(), int(num), filename)
    except ValueError:
        return (stem.lower(), 0, filename)


def _sha256_file(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            block = f.read(chunk)
            if not block:
                break
            h.update(block)
    return h.hexdigest()


def content_digest(vdir):
    """SHA-256 от списка «путь<TAB>sha256 файла» по всем файлам варианта."""
    vdir = Path(vdir)
    lines = []
    for p in sorted(vdir.rglob("*")):
        if p.is_file() and p.name != MARKER:
            rel = p.relative_to(vdir).as_posix()
            lines.append("%s\t%s\n" % (rel, _sha256_file(str(p))))
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest()


def write_metadata(vdir, variant, breeds, source="release"):
    """Пишет labels.csv, variant.json и README.md по содержимому папки варианта."""
    vdir = Path(vdir)
    breeds = sort_breeds(breeds)
    class_ids = dict((b, i) for i, b in enumerate(breeds))
    images = sorted((p.name for p in (vdir / "images").iterdir() if p.is_file()), key=natural_key)
    xml_stems = set(p.stem for p in (vdir / "annotations" / "xmls").glob("*.xml"))
    tri_stems = set(p.stem for p in (vdir / "annotations" / "trimaps").glob("*.png"))
    per_breed = dict((b, {"images": 0, "boxes": 0, "trimaps": 0}) for b in breeds)
    rows = []
    for fn in images:
        stem = os.path.splitext(fn)[0]
        b = breed_of(stem)
        if b not in class_ids:
            raise GetDataError("Файл %s не относится к породам варианта" % fn)
        rows.append((fn, b, species_of(b), class_ids[b]))
        per_breed[b]["images"] += 1
        per_breed[b]["boxes"] += int(stem in xml_stems)
        per_breed[b]["trimaps"] += int(stem in tri_stems)
    with open(str(vdir / "labels.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["filename", "breed", "species", "class_id"])
        w.writerows(rows)
    info = {
        "variant": int(variant),
        "dataset_version": DATASET_VERSION,
        "source": source,
        "breeds": breeds,
        "species": dict((b, species_of(b)) for b in breeds),
        "class_ids": class_ids,
        "names_ru": dict((b, BREEDS[b][1]) for b in breeds),
        "n_images": len(rows),
        "n_boxes": sum(v["boxes"] for v in per_breed.values()),
        "n_trimaps": sum(v["trimaps"] for v in per_breed.values()),
        "per_breed": per_breed,
        "dataset": "Oxford-IIIT Pet",
        "dataset_url": "https://www.robots.ox.ac.uk/~vgg/data/pets/",
        "license": "CC BY-SA 4.0",
        "citation": "O. M. Parkhi, A. Vedaldi, A. Zisserman, C. V. Jawahar. Cats and Dogs. "
                    "IEEE Conference on Computer Vision and Pattern Recognition (CVPR), 2012.",
    }
    with open(str(vdir / "variant.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(info, f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(str(vdir / "README.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(make_readme(info))
    return info


