def _official_archives(dest, official_source):
    src = official_source or OFFICIAL_URL
    paths = {}
    if not str(src).startswith(("http://", "https://")):
        for name in OFFICIAL_FILES:
            p = Path(src).expanduser() / name
            if not p.is_file():
                raise GetDataError("В папке %s нет файла %s" % (src, name))
            paths[name] = p
        return paths
    cache = dest / ".oxford-pets-cache"
    cache.mkdir(parents=True, exist_ok=True)
    need = sum(s for _, s in OFFICIAL_FILES.values())
    _free_space_check(cache, int(need * 1.3))
    if not str(src).endswith("/"):
        src = str(src) + "/"
    for name, (sha, size) in OFFICIAL_FILES.items():
        p = cache / name
        if p.exists() and p.stat().st_size == size and _sha256_file(str(p)) == sha:
            say("  %s уже скачан" % name)
        else:
            say("  Скачиваю %s%s (%s)" % (src, name, _human(size)))
            download(src + name, p, sha, size, label=name)
        paths[name] = p
    return paths


def build_from_official(n, dest, official_source=None):
    n = _check_variant_number(n)
    spec = VARIANTS[n]
    breeds = set(spec["breeds"])
    dest = Path(dest)
    say("Вариант %02d: сборка из официальных архивов Oxford-IIIT Pet" % n)
    arch = _official_archives(dest, official_source)
    tmp = Path(tempfile.mkdtemp(prefix=".%s-" % vname(n), dir=str(dest)))
    staged = tmp / vname(n)
    for sub in ("images", "annotations/xmls", "annotations/trimaps"):
        (staged / sub).mkdir(parents=True)

    def wanted(stem):
        return breed_of(stem) in breeds and stem not in EXCLUDED_STEMS

    try:
        stems = set()
        say("  Извлекаю изображения...")
        with tarfile.open(str(arch["images.tar.gz"]), "r|gz") as tf:
            for m in tf:
                base = m.name.rsplit("/", 1)[-1]
                if not m.isfile() or base.startswith("._") or not base.endswith(".jpg"):
                    continue
                stem = base[:-4]
                if wanted(stem):
                    with open(str(staged / "images" / base), "wb") as out:
                        shutil.copyfileobj(tf.extractfile(m), out)
                    stems.add(stem)
        say("  Извлекаю разметку...")
        with tarfile.open(str(arch["annotations.tar.gz"]), "r|gz") as tf:
            for m in tf:
                parts = m.name.split("/")
                base = parts[-1]
                if not m.isfile() or base.startswith("._") or len(parts) < 2:
                    continue
                if parts[-2] == "trimaps" and base.endswith(".png") and base[:-4] in stems:
                    target = staged / "annotations" / "trimaps" / base
                elif parts[-2] == "xmls" and base.endswith(".xml") and base[:-4] in stems:
                    target = staged / "annotations" / "xmls" / base
                else:
                    continue
                with open(str(target), "wb") as out:
                    shutil.copyfileobj(tf.extractfile(m), out)
        if not stems:
            raise GetDataError("В архиве изображений не нашлось файлов нужных пород.")
        write_metadata(staged, n, spec["breeds"], source="official")
        _write_marker(staged, n, "official")
        final = dest / vname(n)
        _finalize(staged, tmp, final)
    except (tarfile.TarError, EOFError, zlib.error) as e:
        shutil.rmtree(str(tmp), ignore_errors=True)
        raise GetDataError("Официальный архив повреждён (%s). Удалите папку .oxford-pets-cache и повторите." % e)
    except Exception:
        shutil.rmtree(str(tmp), ignore_errors=True)
        raise
    say("Готово: %s (%d изображений)" % (final, len(stems)))
    say("Вариант собран из официального архива Oxford. Состав может немного отличаться от архива курса.\n"
        "Когда основной источник станет доступен, скачайте вариант заново:\n"
        "  python data/get_data.py --variant %d --force" % n)
    return final


