def say(msg="", end="\n"):
    try:
        sys.stdout.write(msg + end)
    except UnicodeEncodeError:
        enc = sys.stdout.encoding or "ascii"
        sys.stdout.write((msg + end).encode(enc, "replace").decode(enc, "replace"))
    sys.stdout.flush()


