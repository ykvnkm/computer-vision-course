def _check(n, dest):
    n = _check_variant_number(n)
    dest = Path(dest).expanduser().resolve() if dest else _default_dest()
    vdir = dest / vname(n)
    if not vdir.is_dir():
        raise GetDataError("Папки %s нет. Сначала скачайте вариант." % vdir)
    m = _read_marker(vdir) or {}
    got = content_digest(vdir)
    ref = VARIANTS[n].get("content_sha256")
    if m.get("source") == "official":
        say("Вариант собран из официального архива; сравнение с эталоном не проводится.")
        return
    if got == ref:
        say("Вариант %02d в порядке: %s" % (n, vdir))
    else:
        raise GetDataError("Файлы в %s отличаются от эталона. Перекачайте: --force" % vdir)


